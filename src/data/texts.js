export function getTextById(id) {
  return dhammaTexts.find(text => text.id === id);
}

export function getDailyText() {
  const featured = dhammaTexts.filter(text => text.featured);
  const pool = featured.length > 0 ? featured : dhammaTexts;
  const day = Math.floor(Date.now() / 86_400_000);
  return pool[day % pool.length];
}

export function searchTexts(query) {
  const q = query.trim().toLowerCase();
  if (!q) {
    return dhammaTexts;
  }
  return dhammaTexts.filter(text => {
    const haystack = [
      text.title,
      text.paliTitle ?? '',
      text.subtitle,
      ...text.paragraphs,
    ]
      .join(' ')
      .toLowerCase();
    return haystack.includes(q);
  });
}
